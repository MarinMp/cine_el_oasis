-- Catalogo de generos de las peliculas.
CREATE TABLE GENERO (
    ID_GENERO INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(40) NOT NULL,
    CONSTRAINT GENERO_PK PRIMARY KEY (ID_GENERO),
    CONSTRAINT GENERO_NOMBRE_UN UNIQUE (NOMBRE)
);

-- Catalogo de clasificaciones por edad, con la edad minima permitida.
CREATE TABLE CLASIFICACION (
    ID_CLASIFICACION INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(30) NOT NULL,
    EDAD_MINIMA INTEGER NOT NULL,
    CONSTRAINT CLASIFICACION_PK PRIMARY KEY (ID_CLASIFICACION),
    CONSTRAINT CLASIFICACION_NOMBRE_UN UNIQUE (NOMBRE),
    CONSTRAINT CLASIFICACION_EDAD_CK CHECK (EDAD_MINIMA BETWEEN 0 AND 18)
);

-- Catalogo de idiomas originales de las peliculas.
CREATE TABLE IDIOMA (
    ID_IDIOMA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(30) NOT NULL,
    CONSTRAINT IDIOMA_PK PRIMARY KEY (ID_IDIOMA),
    CONSTRAINT IDIOMA_NOMBRE_UN UNIQUE (NOMBRE)
);

-- Catalogo de nacionalidades de actores y directores.
CREATE TABLE NACIONALIDAD (
    ID_NACIONALIDAD INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(50) NOT NULL,
    CONSTRAINT NACIONALIDAD_PK PRIMARY KEY (ID_NACIONALIDAD),
    CONSTRAINT NACIONALIDAD_NOMBRE_UN UNIQUE (NOMBRE)
);

-- Catalogo de roles en un contrato (actor o director).
CREATE TABLE ROL (
    ID_ROL INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(30) NOT NULL,
    CONSTRAINT ROL_PK PRIMARY KEY (ID_ROL),
    CONSTRAINT ROL_NOMBRE_UN UNIQUE (NOMBRE)
);

-- Catalogo de formatos de sala (2D, 3D, VIP y 4D).
CREATE TABLE TIPO_SALA (
    ID_TIPO_SALA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(30) NOT NULL,
    CONSTRAINT TIPO_SALA_PK PRIMARY KEY (ID_TIPO_SALA),
    CONSTRAINT TIPO_SALA_NOMBRE_UN UNIQUE (NOMBRE)
);

-- Catalogo de categorias de tarifa (general, nino, adulto mayor).
CREATE TABLE CATEGORIA_ESPECTADOR (
    ID_CATEGORIA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(30) NOT NULL,
    CONSTRAINT CATEGORIA_ESPECTADOR_PK PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT CATEGORIA_ESPECTADOR_NOMBRE_UN UNIQUE (NOMBRE)
);

-- Catalogo de tipos de documento de identidad (espectadores y staff).
CREATE TABLE TIPO_DOCUMENTO (
    ID_TIPO_DOCUMENTO INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(40) NOT NULL,
    CONSTRAINT TIPO_DOCUMENTO_PK PRIMARY KEY (ID_TIPO_DOCUMENTO),
    CONSTRAINT TIPO_DOCUMENTO_NOMBRE_UN UNIQUE (NOMBRE)
);

-- Catalogo de cargos de los empleados del cine.
CREATE TABLE CARGO (
    ID_CARGO INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(40) NOT NULL,
    CONSTRAINT CARGO_PK PRIMARY KEY (ID_CARGO),
    CONSTRAINT CARGO_NOMBRE_UN UNIQUE (NOMBRE)
);

-- =====================================================================
-- Tablas principales
-- =====================================================================

-- Peliculas en cartelera.
CREATE TABLE PELICULA (
    ID_PELICULA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    TITULO VARCHAR(150) NOT NULL,
    DURACION_MIN INTEGER NOT NULL,
    FECHA_ESTRENO DATE NOT NULL,
    ID_GENERO INTEGER NOT NULL,
    ID_CLASIFICACION INTEGER NOT NULL,
    ID_IDIOMA INTEGER NOT NULL,
    CONSTRAINT PELICULA_PK PRIMARY KEY (ID_PELICULA),
    CONSTRAINT PELICULA_TITULO_ESTRENO_UN UNIQUE (TITULO, FECHA_ESTRENO),
    CONSTRAINT PELICULA_DURACION_CK CHECK (DURACION_MIN BETWEEN 1 AND 300),
    CONSTRAINT PELICULA_GENERO_FK FOREIGN KEY (ID_GENERO)
        REFERENCES GENERO (ID_GENERO),
    CONSTRAINT PELICULA_CLASIFICACION_FK FOREIGN KEY (ID_CLASIFICACION)
        REFERENCES CLASIFICACION (ID_CLASIFICACION),
    CONSTRAINT PELICULA_IDIOMA_FK FOREIGN KEY (ID_IDIOMA)
        REFERENCES IDIOMA (ID_IDIOMA)
);

-- Personas que participan en las peliculas como actores o directores.
CREATE TABLE ACTOR_DIRECTOR (
    ID_PERSONA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    PRIMER_NOMBRE VARCHAR(40) NOT NULL,
    SEGUNDO_NOMBRE VARCHAR(40),
    PRIMER_APELLIDO VARCHAR(40) NOT NULL,
    SEGUNDO_APELLIDO VARCHAR(40),
    ID_NACIONALIDAD INTEGER NOT NULL,
    CONSTRAINT ACTOR_DIRECTOR_PK PRIMARY KEY (ID_PERSONA),
    -- No se registra dos veces la misma persona con la misma nacionalidad
    CONSTRAINT ACTOR_DIRECTOR_PERSONA_UN UNIQUE NULLS NOT DISTINCT
        (PRIMER_NOMBRE, SEGUNDO_NOMBRE, PRIMER_APELLIDO, SEGUNDO_APELLIDO, ID_NACIONALIDAD),
    CONSTRAINT ACTOR_DIRECTOR_NACIONALIDAD_FK FOREIGN KEY (ID_NACIONALIDAD)
        REFERENCES NACIONALIDAD (ID_NACIONALIDAD)
);

-- Participacion de una persona en una pelicula con un rol, fechas y valor.
CREATE TABLE CONTRATO (
    ID_CONTRATO INTEGER GENERATED BY DEFAULT AS IDENTITY,
    PERSONAJE VARCHAR(80),
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,
    VALOR NUMERIC(14,2) NOT NULL,
    ID_PERSONA INTEGER NOT NULL,
    ID_PELICULA INTEGER NOT NULL,
    ID_ROL INTEGER NOT NULL,
    CONSTRAINT CONTRATO_PK PRIMARY KEY (ID_CONTRATO),
    CONSTRAINT CONTRATO_PERSONA_PELICULA_ROL_UN UNIQUE (ID_PERSONA, ID_PELICULA, ID_ROL),
    CONSTRAINT CONTRATO_FECHAS_CK CHECK (FECHA_FIN >= FECHA_INICIO),
    CONSTRAINT CONTRATO_VALOR_CK CHECK (VALOR > 0),
    CONSTRAINT CONTRATO_ACTOR_DIRECTOR_FK FOREIGN KEY (ID_PERSONA)
        REFERENCES ACTOR_DIRECTOR (ID_PERSONA),
    CONSTRAINT CONTRATO_PELICULA_FK FOREIGN KEY (ID_PELICULA)
        REFERENCES PELICULA (ID_PELICULA),
    CONSTRAINT CONTRATO_ROL_FK FOREIGN KEY (ID_ROL)
        REFERENCES ROL (ID_ROL)
);

-- Las salas del cine con su tipo, capacidad y estado.
CREATE TABLE SALA (
    ID_SALA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(40) NOT NULL,
    CAPACIDAD INTEGER NOT NULL,
    ESTADO VARCHAR(15) NOT NULL DEFAULT 'ACTIVA',
    ID_TIPO_SALA INTEGER NOT NULL,
    CONSTRAINT SALA_PK PRIMARY KEY (ID_SALA),
    CONSTRAINT SALA_NOMBRE_UN UNIQUE (NOMBRE),
    CONSTRAINT SALA_CAPACIDAD_CK CHECK (CAPACIDAD > 0),
    CONSTRAINT SALA_ESTADO_CK CHECK (ESTADO IN ('ACTIVA', 'MANTENIMIENTO')),
    CONSTRAINT SALA_TIPO_SALA_FK FOREIGN KEY (ID_TIPO_SALA)
        REFERENCES TIPO_SALA (ID_TIPO_SALA)
);

-- Proyeccion de una pelicula en una sala.
CREATE TABLE FUNCION (
    ID_FUNCION INTEGER GENERATED BY DEFAULT AS IDENTITY,
    FECHA DATE NOT NULL,
    HORA_INICIO TIME NOT NULL,
    HORA_FIN TIME NOT NULL,
    VERSION_PROYECCION VARCHAR(25) NOT NULL,
    ID_PELICULA INTEGER NOT NULL,
    ID_SALA INTEGER NOT NULL,
    CONSTRAINT FUNCION_PK PRIMARY KEY (ID_FUNCION),
    CONSTRAINT FUNCION_SALA_HORA_UN UNIQUE (ID_SALA, FECHA, HORA_INICIO),
    -- Toda funcion debe terminar el mismo dia en que empieza
    CONSTRAINT FUNCION_HORAS_CK CHECK (HORA_FIN > HORA_INICIO),
    CONSTRAINT FUNCION_VERSION_CK CHECK (VERSION_PROYECCION IN (
        'ORIGINAL', 'ORIGINAL SUBTITULADA', 'DOBLADA AL ESPANOL')),
    CONSTRAINT FUNCION_PELICULA_FK FOREIGN KEY (ID_PELICULA)
        REFERENCES PELICULA (ID_PELICULA),
    CONSTRAINT FUNCION_SALA_FK FOREIGN KEY (ID_SALA)
        REFERENCES SALA (ID_SALA)
);

-- Precio base de la boleta segun tipo de sala y categoria de espectador.
CREATE TABLE TIPO_BOLETA (
    ID_TIPO_BOLETA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    PRECIO_BASE NUMERIC(10,2) NOT NULL,
    ID_TIPO_SALA INTEGER NOT NULL,
    ID_CATEGORIA INTEGER NOT NULL,
    CONSTRAINT TIPO_BOLETA_PK PRIMARY KEY (ID_TIPO_BOLETA),
    CONSTRAINT TIPO_BOLETA_SALA_CATEGORIA_UN UNIQUE (ID_TIPO_SALA, ID_CATEGORIA),
    CONSTRAINT TIPO_BOLETA_PRECIO_CK CHECK (PRECIO_BASE > 0),
    CONSTRAINT TIPO_BOLETA_TIPO_SALA_FK FOREIGN KEY (ID_TIPO_SALA)
        REFERENCES TIPO_SALA (ID_TIPO_SALA),
    CONSTRAINT TIPO_BOLETA_CATEGORIA_ESPECTADOR_FK FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIA_ESPECTADOR (ID_CATEGORIA)
);

-- Clientes registrados del cine.
CREATE TABLE ESPECTADOR (
    ID_ESPECTADOR INTEGER GENERATED BY DEFAULT AS IDENTITY,
    DOCUMENTO VARCHAR(20) NOT NULL,
    PRIMER_NOMBRE VARCHAR(40) NOT NULL,
    SEGUNDO_NOMBRE VARCHAR(40),
    PRIMER_APELLIDO VARCHAR(40) NOT NULL,
    SEGUNDO_APELLIDO VARCHAR(40),
    CORREO VARCHAR(100) NOT NULL,
    TELEFONO VARCHAR(15),
    ID_TIPO_DOCUMENTO INTEGER NOT NULL,
    CONSTRAINT ESPECTADOR_PK PRIMARY KEY (ID_ESPECTADOR),
    CONSTRAINT ESPECTADOR_DOCUMENTO_UN UNIQUE (DOCUMENTO),
    CONSTRAINT ESPECTADOR_CORREO_UN UNIQUE (CORREO),
    CONSTRAINT ESPECTADOR_TELEFONO_UN UNIQUE (TELEFONO),
    -- Correo en minusculas con formato nombre@dominio.ext
    CONSTRAINT ESPECTADOR_CORREO_CK CHECK (CORREO ~ '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$'),
    -- Telefono de exactamente 10 numeros
    CONSTRAINT ESPECTADOR_TELEFONO_CK CHECK (TELEFONO ~ '^[0-9]{10}$'),
    CONSTRAINT ESPECTADOR_TIPO_DOCUMENTO_FK FOREIGN KEY (ID_TIPO_DOCUMENTO)
        REFERENCES TIPO_DOCUMENTO (ID_TIPO_DOCUMENTO)
);

-- Empleados del cine con su cargo y estado.
CREATE TABLE STAFF (
    ID_STAFF INTEGER GENERATED BY DEFAULT AS IDENTITY,
    DOCUMENTO VARCHAR(20) NOT NULL,
    PRIMER_NOMBRE VARCHAR(40) NOT NULL,
    SEGUNDO_NOMBRE VARCHAR(40),
    PRIMER_APELLIDO VARCHAR(40) NOT NULL,
    SEGUNDO_APELLIDO VARCHAR(40),
    TELEFONO VARCHAR(15),
    FECHA_INGRESO DATE NOT NULL,
    ESTADO VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    ID_TIPO_DOCUMENTO INTEGER NOT NULL,
    ID_CARGO INTEGER NOT NULL,
    CONSTRAINT STAFF_PK PRIMARY KEY (ID_STAFF),
    CONSTRAINT STAFF_DOCUMENTO_UN UNIQUE (DOCUMENTO),
    CONSTRAINT STAFF_TELEFONO_UN UNIQUE (TELEFONO),
    CONSTRAINT STAFF_ESTADO_CK CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),
    -- Telefono de exactamente 10 numeros
    CONSTRAINT STAFF_TELEFONO_CK CHECK (TELEFONO ~ '^[0-9]{10}$'),
    -- La fecha de ingreso no puede ser posterior a hoy
    CONSTRAINT STAFF_FECHA_INGRESO_CK CHECK (FECHA_INGRESO <= CURRENT_DATE),
    CONSTRAINT STAFF_TIPO_DOCUMENTO_FK FOREIGN KEY (ID_TIPO_DOCUMENTO)
        REFERENCES TIPO_DOCUMENTO (ID_TIPO_DOCUMENTO),
    CONSTRAINT STAFF_CARGO_FK FOREIGN KEY (ID_CARGO)
        REFERENCES CARGO (ID_CARGO)
);

-- Compra de boletas en taquilla o en linea.
CREATE TABLE VENTA (
    ID_VENTA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    FECHA_HORA TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CANAL VARCHAR(10) NOT NULL,
    MEDIO_PAGO VARCHAR(20) NOT NULL,
    TOTAL NUMERIC(12,2) NOT NULL DEFAULT 0,
    ID_ESPECTADOR INTEGER NOT NULL,
    ID_FUNCION INTEGER NOT NULL,
    ID_STAFF INTEGER,
    CONSTRAINT VENTA_PK PRIMARY KEY (ID_VENTA),
    CONSTRAINT VENTA_CANAL_CK CHECK (CANAL IN ('TAQUILLA', 'EN LINEA')),
    CONSTRAINT VENTA_MEDIO_PAGO_CK CHECK (MEDIO_PAGO IN (
        'EFECTIVO', 'TARJETA DEBITO', 'TARJETA CREDITO', 'TRANSFERENCIA'
    )),
    CONSTRAINT VENTA_TOTAL_CK CHECK (TOTAL >= 0),
    -- En taquilla la venta la registra un empleado, pero en línea no hay empleado.	
    CONSTRAINT VENTA_CANAL_STAFF_CK CHECK (
        (CANAL = 'TAQUILLA' AND ID_STAFF IS NOT NULL) OR
        (CANAL = 'EN LINEA' AND ID_STAFF IS NULL)
    ),
    CONSTRAINT VENTA_ESPECTADOR_FK FOREIGN KEY (ID_ESPECTADOR)
        REFERENCES ESPECTADOR (ID_ESPECTADOR),
    CONSTRAINT VENTA_FUNCION_FK FOREIGN KEY (ID_FUNCION)
        REFERENCES FUNCION (ID_FUNCION),
    CONSTRAINT VENTA_STAFF_FK FOREIGN KEY (ID_STAFF)
        REFERENCES STAFF (ID_STAFF)
);

-- =====================================================================
-- Tablas intermedias
-- =====================================================================

-- Detalle de la venta (M:N entre VENTA - TIPO_BOLETA)
CREATE TABLE DETALLE_VENTA (
    ID_VENTA INTEGER NOT NULL,
    ID_TIPO_BOLETA INTEGER NOT NULL,
    CANTIDAD INTEGER NOT NULL,
    PRECIO_UNITARIO NUMERIC(10,2) NOT NULL,
    CONSTRAINT DETALLE_VENTA_PK PRIMARY KEY (ID_VENTA, ID_TIPO_BOLETA),
    CONSTRAINT DETALLE_VENTA_CANTIDAD_CK CHECK (CANTIDAD BETWEEN 1 AND 10),
    CONSTRAINT DETALLE_VENTA_PRECIO_CK CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT DETALLE_VENTA_VENTA_FK FOREIGN KEY (ID_VENTA)
        REFERENCES VENTA (ID_VENTA),
    CONSTRAINT DETALLE_VENTA_TIPO_BOLETA_FK FOREIGN KEY (ID_TIPO_BOLETA)
        REFERENCES TIPO_BOLETA (ID_TIPO_BOLETA)
);

-- Empleados asignados a cada funcion con su tarea (M:N entre FUNCION - STAFF)
CREATE TABLE ASIGNACION (
    ID_FUNCION INTEGER NOT NULL,
    ID_STAFF INTEGER NOT NULL,
    TAREA VARCHAR(60) NOT NULL,
    CONSTRAINT ASIGNACION_PK PRIMARY KEY (ID_FUNCION, ID_STAFF),
    CONSTRAINT ASIGNACION_FUNCION_FK FOREIGN KEY (ID_FUNCION)
        REFERENCES FUNCION (ID_FUNCION),
    CONSTRAINT ASIGNACION_STAFF_FK FOREIGN KEY (ID_STAFF)
        REFERENCES STAFF (ID_STAFF)
);

